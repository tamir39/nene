import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// Connects only to this repository's local Supabase stack. Never prints keys.
const root = fileURLToPath(new URL('../', import.meta.url));
const backendEnv = path.join(root, 'backend', '.env');
const appConfig = path.join(root, 'app', 'config', 'local.json');

try {
  if (existsSync(backendEnv) || existsSync(appConfig)) {
    throw new Error('Local configuration already exists. Keep it and edit it explicitly; no files were overwritten.');
  }
  const statusText = execFileSync(process.execPath, [
    path.join(root, 'node_modules', 'supabase', 'dist', 'supabase.js'),
    'status', '--workdir', 'infrastructure', '--output', 'json',
  ], { cwd: root, encoding: 'utf8', timeout: 30_000, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
  const status = JSON.parse(statusText);
  const endpoint = new URL(status.API_URL);
  if (endpoint.protocol !== 'http:' || !['127.0.0.1', 'localhost'].includes(endpoint.hostname) || endpoint.port !== '54321') {
    throw new Error('Expected the local Nene Supabase API on port 54321. No configuration was written.');
  }
  const publicKey = status.PUBLISHABLE_KEY || status.ANON_KEY;
  if (typeof publicKey !== 'string' || !publicKey || publicKey.includes('\n')) {
    throw new Error('Local Supabase did not provide a public client key. No configuration was written.');
  }
  if (!publicKey.startsWith('sb_publishable_')) {
    const payload = JSON.parse(Buffer.from(publicKey.split('.')[1] || '', 'base64url').toString('utf8'));
    if (payload.role !== 'anon') throw new Error('The returned client key is not a public anon key. No configuration was written.');
  }
  execFileSync(process.execPath, [path.join(root, 'infrastructure', 'scripts', 'configure-local-api.mjs')], {
    cwd: root, encoding: 'utf8', timeout: 45_000, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'],
  });
  const databaseEnv = readFileSync(path.join(root, 'infrastructure', '.env.api.local'), 'utf8');
  const databaseUrl = /^DATABASE_URL=(\S+)\r?$/m.exec(databaseEnv)?.[1];
  if (!databaseUrl) throw new Error('Local database configuration was not generated. No app configuration was written.');

  writeFileSync(backendEnv, [
    '# Local development only. Generated by npm run setup:local; never commit.',
    'NODE_ENV=development', 'HOST=127.0.0.1', 'PORT=3000',
    'SUPABASE_URL=http://127.0.0.1:54321', `SUPABASE_PUBLISHABLE_KEY=${publicKey}`,
    `DATABASE_URL=${databaseUrl}`, 'DATABASE_SSL_MODE=disable', '',
  ].join('\n'), { encoding: 'utf8', flag: 'wx', mode: 0o600 });
  mkdirSync(path.dirname(appConfig), { recursive: true });
  writeFileSync(appConfig, `${JSON.stringify({
    API_BASE_URL: 'http://10.0.2.2:3000/api/v1',
    SUPABASE_URL: 'http://10.0.2.2:54321',
    SUPABASE_PUBLISHABLE_KEY: publicKey,
  }, null, 2)}\n`, { encoding: 'utf8', flag: 'wx' });
  console.log('Created ignored backend/.env and app/config/local.json for the Android emulator. No credentials were printed.');
} catch (error) {
  // Subprocess errors can contain local service credentials; never echo them.
  const allowed = error instanceof Error && /^(Local configuration|Expected the local|Local Supabase|The returned client key|Local database configuration)/.test(error.message);
  console.error(allowed ? error.message : 'Local setup failed. Check Docker, npm ci, and npm run db:start; existing configuration is not overwritten.');
  process.exitCode = 1;
}
