import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';

const root = fileURLToPath(new URL('../', import.meta.url));
const previewOrigin = 'http://127.0.0.1:4179';
const loopbackHosts = new Set(['127.0.0.1', 'localhost']);

function localUrl(value, { emulator = false, api = false, port } = {}) {
  if (typeof value !== 'string') throw new Error('Invalid local URL.');
  const url = new URL(value);
  const hosts = emulator ? new Set([...loopbackHosts, '10.0.2.2']) : loopbackHosts;
  if (
    url.protocol !== 'http:' ||
    !hosts.has(url.hostname) ||
    url.username || url.password || url.search || url.hash ||
    (api ? !['/api/v1', '/api/v1/'].includes(url.pathname) : url.pathname !== '/') ||
    (port && url.port !== String(port))
  ) {
    throw new Error('Invalid local URL.');
  }
  return url;
}

function isPublicKey(key) {
  if (typeof key !== 'string' || /\s/.test(key)) return false;
  if (/^sb_publishable_[A-Za-z0-9_-]{16,}$/.test(key)) return true;
  const parts = key.split('.');
  if (parts.length !== 3 || parts.some(part => !/^[A-Za-z0-9_-]+$/.test(part))) {
    return false;
  }
  try {
    const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
    // Accidental-secret guard only; server authentication verifies signatures.
    return payload !== null && typeof payload === 'object' && payload.role === 'anon';
  } catch {
    return false;
  }
}

/** Pure validation keeps unsafe targets/keys from reaching either output file. */
export function browserPreviewConfiguration(backend, android) {
  if (!['development', 'test'].includes(backend.NODE_ENV)) {
    throw new Error('Expected an explicit nonproduction backend environment.');
  }
  if (!loopbackHosts.has(backend.HOST)) {
    throw new Error('Expected a loopback API host.');
  }
  if (!/^[1-9]\d{0,4}$/.test(backend.PORT ?? '')) {
    throw new Error('Expected a valid local API port.');
  }
  const apiPort = Number(backend.PORT);
  if (apiPort > 65535 || apiPort === 4179) {
    throw new Error('Expected a valid API port distinct from the preview server.');
  }
  const apiOrigin = localUrl(`http://${backend.HOST}:${apiPort}`).origin;
  const supabase = localUrl(backend.SUPABASE_URL, { port: 54321 });
  // The source must also be an existing local-emulator configuration. Never
  // silently carry a hosted project's client key into this local preview.
  localUrl(android.SUPABASE_URL, { emulator: true, port: 54321 });
  localUrl(android.API_BASE_URL, { emulator: true, api: true });
  const publicKey = android.SUPABASE_PUBLISHABLE_KEY;
  if (!isPublicKey(publicKey)) {
    throw new Error('Expected a public Supabase client key.');
  }

  return {
    config: {
      API_BASE_URL: `${previewOrigin}/api/v1`,
      SUPABASE_URL: supabase.origin,
      SUPABASE_PUBLISHABLE_KEY: publicKey,
    },
    yaml: [
      '# Local preview only. Regenerated by npm run setup:browser; never commit.',
      'server:',
      '  host: "127.0.0.1"',
      '  port: 4179',
      '  proxy:',
      `    - target: "${apiOrigin}/"`,
      '      prefix: "/api/v1/"',
      '',
    ].join('\n'),
  };
}

function main() {
  try {
    const backend = parseEnv(readFileSync(path.join(root, 'backend', '.env'), 'utf8'));
    const android = JSON.parse(
      readFileSync(path.join(root, 'app', 'config', 'local.json'), 'utf8'),
    );
    const { config, yaml } = browserPreviewConfiguration(backend, android);
    const configFolder = path.join(root, 'app', 'config');
    mkdirSync(configFolder, { recursive: true });
    // These two browser files are deliberately regenerable. Android config and
    // backend configuration are inputs only, and no provider calls are made.
    writeFileSync(path.join(root, 'app', 'web_dev_config.yaml'), yaml, {
      encoding: 'utf8', mode: 0o600,
    });
    writeFileSync(
      path.join(configFolder, 'browser.local.json'),
      `${JSON.stringify(config, null, 2)}\n`,
      { encoding: 'utf8', mode: 0o600 },
    );
    console.log('Generated ignored browser preview configuration for http://127.0.0.1:4179. Android configuration unchanged; no keys printed.');
  } catch {
    // Input errors can contain environment values or credentials. Never echo
    // parser/URL errors, file contents, backend secrets or the public key.
    console.error('Browser setup failed. Check the existing local backend/.env and app/config/local.json: use development/test, a loopback API host, a valid port other than 4179, local Supabase on 54321 and a public client key.');
    process.exitCode = 1;
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main();
}
